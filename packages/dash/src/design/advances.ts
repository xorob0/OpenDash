/**
 * Advance widths in em, measured from the bundled TTFs, for the characters OpenDash draws. They
 * are how a proportional string's width is known before SimHub renders it: SimHub hands the box
 * to WPF as `MaxTextWidth` and clips whatever does not fit, so a label that does not fit must be
 * shortened by the card rather than cut by the renderer.
 *
 * Generated from packages/dash/fonts by `bun tools/measure-font/measure.ts --table <file.ttf>`, one
 * face per file, over ASCII, the symbols the dash draws, and the letters of Latin-1 and Latin
 * Extended-A; regenerate when a font file changes. A character absent from the table, which is one
 * the face does not carry or one outside that set, falls back to `FALLBACK_ADVANCE`.
 */

/** The faces of text: Barlow at both widths, which carry every character the table lists. */
export type TextFace = 'BarlowMedium' | 'BarlowBold' | 'BarlowCondensedSemiBold' | 'BarlowCondensedBold' | 'BarlowCondensedLight';

/**
 * The segment faces a theme draws its LCD in (#204), DSEG7 Classic and DSEG14 Classic. Each glyph is
 * a cell of 0.816 em, the full stop has no advance at all, since it lights the point of the cell
 * before it, and the colon a fifth of one; a character the face does not carry is left out of its
 * table and falls back like any other, WPF drawing it in a face of its own.
 */
export type SegmentFace = 'DSEG7Regular' | 'DSEG7Bold' | 'DSEG14Regular';

export type MeasuredFace = TextFace | SegmentFace;

